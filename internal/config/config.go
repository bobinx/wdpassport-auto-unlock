package config

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const DefaultConfigPath = "/etc/wdpassport.conf"

// Config represents drive auto-unlock configuration.
type Config struct {
	Password   string `json:"password,omitempty"`
	Device     string `json:"device,omitempty"`
	UUID       string `json:"uuid,omitempty"`
	MountPoint string `json:"mount_point,omitempty"`
	Timeout    int    `json:"timeout"`
}

// Load reads and parses an INI config file.
func Load(path string) (*Config, error) {
	if path == "" {
		path = DefaultConfigPath
	}

	info, err := os.Stat(path)
	if err != nil {
		return nil, err
	}

	// Warn if permissions are looser than 0600
	perm := info.Mode().Perm()
	if perm&0077 != 0 {
		fmt.Fprintf(os.Stderr, "Warning: %s has loose permissions (%04o). Expected 0600.\n", path, perm)
	}

	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	cfg := &Config{
		Timeout: 30,
	}

	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") || strings.HasPrefix(line, "[") {
			continue
		}

		parts := strings.SplitN(line, "=", 2)
		if len(parts) != 2 {
			continue
		}

		key := strings.ToLower(strings.TrimSpace(parts[0]))
		val := strings.TrimSpace(parts[1])

		// Strip inline quotes if present
		if len(val) >= 2 && ((val[0] == '"' && val[len(val)-1] == '"') || (val[0] == '\'' && val[len(val)-1] == '\'')) {
			val = val[1 : len(val)-1]
		}

		switch key {
		case "password":
			cfg.Password = val
		case "device":
			cfg.Device = val
		case "uuid":
			cfg.UUID = val
		case "mount_point", "mountpoint":
			cfg.MountPoint = val
		case "timeout":
			if t, err := strconv.Atoi(val); err == nil && t > 0 {
				cfg.Timeout = t
			}
		}
	}

	return cfg, scanner.Err()
}

// Save writes configuration to file with mode 0600.
func Save(path string, cfg *Config) error {
	if path == "" {
		path = DefaultConfigPath
	}

	dir := filepath.Dir(path)
	if dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0755); err != nil {
			return err
		}
	}

	var sb strings.Builder
	sb.WriteString("# /etc/wdpassport.conf\n")
	sb.WriteString("# Generated by wd-auto-unlock config\n\n")
	sb.WriteString("[wdpassport]\n")
	sb.WriteString(fmt.Sprintf("password = %s\n", cfg.Password))

	if cfg.Device != "" {
		sb.WriteString(fmt.Sprintf("device = %s\n", cfg.Device))
	}
	if cfg.UUID != "" {
		sb.WriteString(fmt.Sprintf("uuid = %s\n", cfg.UUID))
	}
	if cfg.MountPoint != "" {
		sb.WriteString(fmt.Sprintf("mount_point = %s\n", cfg.MountPoint))
	}
	if cfg.Timeout > 0 {
		sb.WriteString(fmt.Sprintf("timeout = %d\n", cfg.Timeout))
	}

	return os.WriteFile(path, []byte(sb.String()), 0600)
}
